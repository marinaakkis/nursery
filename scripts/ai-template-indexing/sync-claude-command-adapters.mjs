#!/usr/bin/env node

// Generates thin Claude Code command adapters in `.claude/commands/` from the
// canonical Cursor commands in `.cursor/commands/`. Each adapter references the
// canonical command file instead of copying it, so the two agents never drift.
//
// Mirrors scripts/ai-template-indexing/sync-claude-skill-adapters.mjs (skills) for commands.
//
// Ownership model:
//   - `.cursor/commands/*.md` is the single source of truth.
//   - `.claude/commands/*.md` adapters are generated and must not be hand-edited.
//   - A genuinely Claude-only command is preserved by adding `claude-specific: true`
//     to its YAML frontmatter; such files are never deleted or overwritten.

import { readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const canonicalRoot = join(root, ".cursor", "commands");
const adapterRoot = join(root, ".claude", "commands");

const GENERATED_MARKER = "GENERATED by scripts/ai-template-indexing/sync-claude-command-adapters.mjs";

function read(path) {
  return readFileSync(path, "utf8");
}

function normalize(text) {
  return text.replace(/^﻿/, "").replace(/\r\n/g, "\n");
}

function frontmatter(text) {
  const normalized = normalize(text);
  if (!normalized.startsWith("---\n")) return null;
  const end = normalized.indexOf("\n---", 4);
  if (end === -1) return null;
  return normalized.slice(4, end).trimEnd();
}

function field(fm, name) {
  if (!fm) return "";
  const line = fm.split("\n").find((value) => value.startsWith(`${name}:`));
  return line ? line.slice(name.length + 1).trim().replace(/^["']|["']$/g, "") : "";
}

function isClaudeSpecific(text) {
  return field(frontmatter(text), "claude-specific").toLowerCase() === "true";
}

function isGenerated(text) {
  return normalize(text).includes(GENERATED_MARKER);
}

function firstHeading(text) {
  const line = normalize(text)
    .split("\n")
    .find((value) => /^#\s+/.test(value));
  return line ? line.replace(/^#\s+/, "").trim() : "";
}

function mdFiles(dir) {
  return readdirSync(dir)
    .filter((name) => name.endsWith(".md"))
    .filter((name) => statSync(join(dir, name)).isFile())
    .sort();
}

function adapter(name, description) {
  const desc = description || `Claude Code adapter for ${name}.`;
  const canonical = `.cursor/commands/${name}.md`;
  return `---
description: ${JSON.stringify(desc)}
---

<!-- ${GENERATED_MARKER} — DO NOT EDIT. Canonical source: ${canonical} -->

# Claude Code Command Adapter

This is a generated adapter for the canonical shared command:

\`${canonical}\`

When this command runs:

1. Read the canonical command file above.
2. Follow its instructions exactly; the text below is the command arguments.
3. Do not treat this adapter as the source of truth. On any divergence the
   canonical file wins.

Regenerate adapters with:

\`\`\`bash
node scripts/ai-template-indexing/sync-claude-command-adapters.mjs
\`\`\`

---

Arguments: $ARGUMENTS
`;
}

if (!statSync(canonicalRoot).isDirectory()) {
  throw new Error(`missing canonical commands directory: ${canonicalRoot}`);
}

// Preserve hand-authored Claude-only commands; remove every generated adapter so
// renamed/deleted canonical commands do not leave stale files behind.
const preserved = new Set();
for (const name of mdFiles(adapterRoot)) {
  const path = join(adapterRoot, name);
  const text = read(path);
  if (isClaudeSpecific(text)) {
    preserved.add(name);
    continue;
  }
  if (isGenerated(text)) {
    rmSync(path);
    continue;
  }
  // Unmanaged, non-generated file with no opt-out marker: a stale hand copy.
  // It is replaced below if a canonical command of the same name exists.
  rmSync(path);
}

let written = 0;
const shadowed = [];
for (const name of mdFiles(canonicalRoot)) {
  if (preserved.has(name)) {
    shadowed.push(name);
    continue;
  }
  const text = read(join(canonicalRoot, name));
  writeFileSync(join(adapterRoot, name), adapter(name.replace(/\.md$/, ""), firstHeading(text)), "utf8");
  written += 1;
}

console.log(`Synced ${written} Claude command adapters.`);
if (preserved.size) {
  console.log(`Preserved ${preserved.size} claude-specific command(s): ${[...preserved].join(", ")}`);
}
if (shadowed.length) {
  console.log(`Note: canonical command(s) shadowed by a claude-specific override: ${shadowed.join(", ")}`);
}
