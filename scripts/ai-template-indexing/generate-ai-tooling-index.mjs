#!/usr/bin/env node

import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = process.cwd();

function exists(path) {
  try {
    statSync(join(root, path));
    return true;
  } catch {
    return false;
  }
}

function read(path) {
  return readFileSync(join(root, path), "utf8");
}

function files(dir, predicate = () => true) {
  if (!exists(dir)) return [];
  return readdirSync(join(root, dir))
    .map((name) => join(dir, name))
    .filter((path) => statSync(join(root, path)).isFile())
    .filter(predicate)
    .sort();
}

function dirs(dir) {
  if (!exists(dir)) return [];
  return readdirSync(join(root, dir))
    .map((name) => join(dir, name))
    .filter((path) => statSync(join(root, path)).isDirectory())
    .sort();
}

function frontmatter(text) {
  const normalized = text.replace(/^\uFEFF/, "").replace(/\r\n/g, "\n");
  if (!normalized.startsWith("---\n")) return "";
  const end = normalized.indexOf("\n---", 4);
  return end === -1 ? "" : normalized.slice(4, end).trimEnd();
}

function field(fm, name) {
  const lines = fm.split("\n");
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    if (!line.startsWith(`${name}:`)) continue;

    const inline = line.slice(name.length + 1).trim();

    // Block scalar header: folded (`>`) or literal (`|`), with optional
    // chomping (`-`/`+`) and indentation indicator (digit). Gather the
    // following indented/blank lines and fold them into one line — every
    // value lands in a single markdown table cell, so newlines are collapsed.
    if (/^[>|][+-]?\d*$/.test(inline)) {
      const values = [];
      for (let j = i + 1; j < lines.length; j += 1) {
        const next = lines[j];
        if (next.trim() === "") {
          values.push("");
          continue;
        }
        if (!/^\s/.test(next)) break;
        values.push(next.trim());
      }
      return values.join(" ").replace(/\s+/g, " ").trim();
    }

    // Plain or quoted scalar on the same line.
    return inline.replace(/^["']|["']$/g, "");
  }
  return "";
}

function firstHeading(path) {
  const line = read(path).split("\n").find((value) => /^#\s+/.test(value));
  return line ? line.replace(/^#\s+/, "").trim() : "";
}

function table(headers, rows) {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

const skills = dirs(".agents/skills").map((dir) => {
  const path = `${dir}/SKILL.md`;
  const fm = frontmatter(read(path));
  return [
    field(fm, "name") || dir.split("/").pop(),
    path,
    field(fm, "description").slice(0, 180),
  ];
});

const rules = files(".cursor/rules", (path) => path.endsWith(".mdc")).map((path) => {
  const fm = frontmatter(read(path));
  return [
    path.split("/").pop().replace(/\.mdc$/, ""),
    path,
    field(fm, "alwaysApply") || "false",
    field(fm, "description").slice(0, 160),
  ];
});

const cursorCommands = files(".cursor/commands", (path) => path.endsWith(".md")).map((path) => [
  path.split("/").pop().replace(/\.md$/, ""),
  path,
  firstHeading(path),
]);

const claudeCommands = files(".claude/commands", (path) => path.endsWith(".md")).map((path) => [
  path.split("/").pop().replace(/\.md$/, ""),
  path,
  firstHeading(path),
]);

const opencodeCommands = files(".opencode/commands", (path) => path.endsWith(".md")).map((path) => [
  path.split("/").pop().replace(/\.md$/, ""),
  path,
  firstHeading(path),
]);

const hooks = [
  ["Cursor security events", ".cursor/hooks.json", "Runs pinned gitleaks-hook v2.0.1 with the native Cursor protocol"],
  ["Claude security events", ".claude/settings.json", "Runs pinned gitleaks-hook v2.0.1 with the native Claude Code protocol"],
  ["Codex security events", ".codex/hooks.json", "Runs pinned gitleaks-hook v2.0.1 with the native Codex protocol"],
  ["Git pre-commit", ".githooks/pre-commit", "Validates integration passports"],
  ["Git pre-push", ".githooks/pre-push", "Validates integration passports"],
];

const content = `# AI Tooling Index

Generated by \`node scripts/ai-template-indexing/generate-ai-tooling-index.mjs\`.

## Summary

- Canonical skills: ${skills.length}
- Cursor rules: ${rules.length}
- Cursor commands: ${cursorCommands.length}
- Claude commands: ${claudeCommands.length}
- OpenCode commands: ${opencodeCommands.length}
- Hook entrypoints: ${hooks.length}

## Canonical Skills

${table(["Name", "Path", "Description"], skills)}

## Cursor Rules

${table(["Rule", "Path", "alwaysApply", "Description"], rules)}

## Cursor Commands

${table(["Command", "Path", "Heading"], cursorCommands)}

## Claude Commands

${table(["Command", "Path", "Heading"], claudeCommands)}

## OpenCode Commands

${table(["Command", "Path", "Heading"], opencodeCommands)}

## Hooks

${table(["Entry", "Path", "Purpose"], hooks)}
`;

const outPath = join(root, "docs", "ai-tooling-index.md");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, content, "utf8");
console.log(`Wrote ${outPath}`);
