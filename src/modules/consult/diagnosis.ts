/** Названия света — для замечания про несовпадение места и требований. */
const LIGHT_WORD: Record<string, string> = { sun: "солнце", partial: "полутень", shade: "тень" };

/** Вопрос не про растение, а про заказ или доставку — не наша зона. */
const OFF_TOPIC = [
  "заказ", "доставк", "курьер", "оплат", "верну", "возврат", "чек", "скидк", "когда привезут",
];

const normalize = (text: string): string => text.toLowerCase().replace(/ё/g, "е");
const hasAny = (text: string, keys: string[]): boolean =>
  keys.some((key) => text.includes(normalize(key)));

export type DiagnosisResult =
  | { kind: "refuse"; message: string; hint: string }
  | { kind: "diagnosis"; diagnosis: Diagnosis };

export function diagnose(text: string, plant: PlantFacts | null): DiagnosisResult {
  const normalized = normalize(text);

  if (hasAny(normalized, OFF_TOPIC) && !SYMPTOMS.some((s) => hasAny(normalized, s.keys))) {
    return {
      kind: "refuse",
      message: "Это вопрос про заказ, а не про растение — тут я не помощник.",
      hint: "По заказу и доставке ответит менеджер питомника: статус виден на странице заказа.",
    };
  }

  const found = SYMPTOMS.filter((symptom) => hasAny(normalized, symptom.keys));

  if (found.length === 0) {
    return {
      kind: "refuse",
      message: "По описанию не понял, что именно происходит с растением.",
      hint: "Спросите у покупателя, что видно на листьях и когда это началось, — тогда попробую снова.",
    };
  }

  const primary = found[0];
  const steps = primary.steps.slice(0, 3);
  const matched = found.map((symptom) => symptom.name);

  const notes: string[] = [];
  if (plant) {
    notes.push(`${plant.nameRu}: место — ${LIGHT_WORD[plant.light] ?? plant.light}, почва — ${plant.soil}.`);
    if (primary.name === "растение не растёт" && plant.light === "shade") {
      notes.push("Растение теневое, значит нехватка света маловероятна — смотрите на почву и возраст посадки.");
    }
    if (primary.name === "жёлтые листья" && plant.soil.includes("кисл")) {
      notes.push("Почва нужна кислая: на нейтральной такое растение желтеет от нехватки железа.");
    }
  }

  const body = [
    `Похоже на «${primary.name}».`,
    primary.cause,
    ...(notes.length > 0 ? [notes.join(" ")] : []),
    "Что сделать:",
    ...steps.map((step, index) => `${index + 1}. ${step}`),
  ].join("\n");

  const rationale = [
    `Совпали признаки: ${matched.join(", ")}.`,
    plant
      ? `Требования растения взяты из карточки: свет — ${LIGHT_WORD[plant.light] ?? plant.light}, зона ${plant.minZone}, почва — ${plant.soil}.`
      : "Растение к вопросу не привязано, поэтому разбор общий.",
    found.length > 1
      ? "Признаков несколько — взят первый по тексту, остальные стоит проверить отдельно."
      : "Признак один, разночтений нет.",
  ].join(" ");

  return {
    kind: "diagnosis",
    diagnosis: {
      body,
      rationale,
      confidence: plant ? primary.confidence : Math.max(1, primary.confidence - 1),
      askAbout: primary.ask,
      matched,
    },
  };
}
